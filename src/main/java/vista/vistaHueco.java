    //Metodo para mostrar los huecos en el calendario
    public void mostrarHuecos(List<Hueco> huecos) {
        //Creacion del Map para guardar el estado del dia 
        Map<LocalDate, String> mapa = new HashMap<>();

        //Se recorre la lista de los huecos para guardar su estado 
        for (modelo.vo.Hueco h : huecos) {
            LocalDate dia = h.getFecha().toLocalDate();
            String previo = mapa.get(dia);
            mapa.put(dia, masFuerte(previo, h.getEstado()));
        }
        calendario.setEstados(mapa);
    }

    //Metodo para elegir el estado de mayor prioridad 
    private String masFuerte(String a, String b) {
        //En caso de no haber un estado previo se devuelve el nuevo 
        if (a == null) {
            return b;
        }

        //Se establecen las prioridades del tipo de los huecos para ver que pesa mas que otros
        if ("reservado".equals(a) || "reservado".equals(b)) {
            return "reservado";
        }
        if ("solicitado".equals(a) || "solicitado".equals(b)) {
            return "solicitado";
        }
        if ("bloqueado".equals(a) || "bloqueado".equals(b)) {
            return "bloqueado";
        }
        return "libre";
    }

