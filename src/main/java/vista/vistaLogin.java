    //Metodo para el selector de idioma
    private void cmbIdiomaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbIdiomaActionPerformed
        String codigo = cmbIdioma.getSelectedIndex() == 1 ? "gl" : "es";
        controlador.idioma.set(codigo);
        //Llamo al metodo guardar de preferencias para que se quede guardada la configuracion del usuario
        Preferencias.guardar("idioma", codigo);
        aplicarTextos();
    }//GEN-LAST:event_cmbIdiomaActionPerformed

    //Metodo para cambio de idioma con el combo
    public void aplicarTextos() {
        avisoMail = idioma.t("login.mail");
        avisoClave = idioma.t("login.contrasenia");
        if (!avisosListos) {
            preparar(mailField, true);
            preparar(passField, false);
            avisosListos = true;
        }
        if (mailField.getText().isEmpty() || mailField.getForeground().equals(java.awt.Color.GRAY)) {
            mailField.setText(avisoMail);
            mailField.setForeground(java.awt.Color.GRAY);
        }
        if (new String(passField.getPassword()).isEmpty()
                || passField.getForeground().equals(java.awt.Color.GRAY)) {
            passField.setEchoChar((char) 0);
            passField.setText(avisoClave);
            passField.setForeground(java.awt.Color.GRAY);
        }
    }

    private void preparar(javax.swing.JTextField campo, boolean esMail) {
        campo.addFocusListener(new java.awt.event.FocusAdapter() {
            public void focusGained(java.awt.event.FocusEvent e) {
                String aviso = esMail ? avisoMail : avisoClave;
                if (campo.getText().equals(aviso)) {
                    campo.setText("");
                    campo.setForeground(java.awt.Color.BLACK);
                    if (campo instanceof javax.swing.JPasswordField) {
                        ((javax.swing.JPasswordField) campo).setEchoChar('•');
                    }
                }
            }

            public void focusLost(java.awt.event.FocusEvent e) {
                if (campo.getText().isEmpty()) {
                    String aviso = esMail ? avisoMail : avisoClave;
                    if (campo instanceof javax.swing.JPasswordField) {
                        ((javax.swing.JPasswordField) campo).setEchoChar((char) 0);
                    }
                    campo.setText(aviso);
                    campo.setForeground(java.awt.Color.GRAY);
                }
            }
        });
    }

