    //Mostrar texto antes de foco y manejarlo segun operacion
    private void aviso(javax.swing.JTextField campo, String texto) {
        campo.setText(texto);
        campo.setForeground(java.awt.Color.GRAY);
        campo.addFocusListener(new FocusAdapter() {
            //Al entrar quita el avisoy activa modo contrasenia en caso de que lo sea
            public void focusGained(FocusEvent e) {
                if (campo.getText().equals(texto)) {
                    campo.setText("");
                    campo.setForeground(Color.BLACK);
                    if (campo instanceof JPasswordField) {
                        ((JPasswordField) campo).setEchoChar('•');
                    }
                }
            }

            //En caso de seguir vacio al salir se vuelve a marcar el aviso
            public void focusLost(java.awt.event.FocusEvent e) {
                if (campo.getText().isEmpty()) {
                    if (campo instanceof javax.swing.JPasswordField) {
                        ((javax.swing.JPasswordField) campo).setEchoChar((char) 0);
                    }
                    campo.setText(texto);
                    campo.setForeground(java.awt.Color.GRAY);
                }
            }
        });
    }

    //Getter de campo de mail
    public String getEmail() {
        String email = mailField.getText().trim();
        if (email.equals(idioma.t("login.mail"))) {
            return "";
        }
        return email;
    }

    //Getter del campo de contrasenia
    public String getClave() {
        String clave = new String(passField.getPassword());
        if (clave.equals(idioma.t("login.contrasenia"))) {
            return "";
        }
        return clave;
    }

