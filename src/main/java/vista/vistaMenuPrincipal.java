    //Carga de la imagen para cada uno de los paneles del "menu principal"
    private static class PanelImagen extends javax.swing.JPanel {

        private java.awt.Image imagen;
        //variable para aplicar zoom a panel y label
        private double zoom = 1.0;

        public PanelImagen(String ruta) {
            java.net.URL url = vistaMenuPrincipal.class.getResource(ruta);
            if (url != null) {
                imagen = new javax.swing.ImageIcon(url).getImage();
            } else {
                System.err.println("No se encuentra la imagen: " + ruta);
            }
        }

        public void setZoom(double zoom) {
            this.zoom = zoom;
            repaint();
        }

        @Override
        protected void paintComponent(java.awt.Graphics g) {
            super.paintComponent(g);
            if (imagen != null) {
                java.awt.Graphics2D g2 = (java.awt.Graphics2D) g.create();
                g2.setRenderingHint(java.awt.RenderingHints.KEY_INTERPOLATION,
                        java.awt.RenderingHints.VALUE_INTERPOLATION_BILINEAR);

                int anchoImg = imagen.getWidth(this);
                int altoImg = imagen.getHeight(this);

                // Escala la imagen sin deformarla hasta cubrir todo el panel, multiplicada por el zoom
                double escala = Math.max((double) getWidth() / anchoImg,
                        (double) getHeight() / altoImg) * zoom;
                int w = (int) (anchoImg * escala);
                int h = (int) (altoImg * escala);

                // Centra la imagen; lo que sobra por los lados se recorta
                int x = (getWidth() - w) / 2;
                int y = (getHeight() - h) / 2;

                g2.drawImage(imagen, x, y, w, h, this);
                g2.dispose();
            }
        }
    }

    //Metodo para activar o desactivar zoom de los paneles
    private void zoom(javax.swing.JPanel panel, javax.swing.JLabel lbl, boolean activo) {
        ((PanelImagen) panel).setZoom(activo ? 1.2 : 1.0);
        lbl.setFont(lbl.getFont().deriveFont(activo ? 27f : 18f));
    }

